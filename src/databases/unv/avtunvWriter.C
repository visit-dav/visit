    struct tm *tm = localtime(&now);
    // Format date and time
    char buffer[24];
    strftime(buffer, sizeof(buffer), "%d-%b-%y   %H:%M:%S", tm);
    
    fprintf(ofile,"%s        15         0         0\n", buffer) ;
