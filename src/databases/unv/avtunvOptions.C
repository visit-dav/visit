//  Function: GetunvWriteOptions
//
//  Purpose:
//      Creates the options for unv writers.
//
//  Important Note:
//      The code below sets up empty options.  If your format does not require
//      write options, no modifications are necessary.
//
//  Programmer: cessenat -- generated by xml2avt
//  Creation:   Sun Oct 12 17:53:15 PST 2025
